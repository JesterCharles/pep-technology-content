package pep.collections;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.fail;

import java.lang.reflect.Method;
import java.util.HashMap;
import java.util.HashSet;
import java.util.Map;
import java.util.Set;
import org.junit.jupiter.api.Test;

class SeatTest {

    /**
     * Fails the test unless Seat is still a class that declares the method itself. A record would
     * generate both methods for you, and a superclass would supply them through methods the compiler
     * writes, so this part asks you to keep Seat a plain class and write both methods in it by hand.
     */
    private static void assertDeclares(String name, Class<?>... parameterTypes) {
        if (Seat.class.isRecord()) {
            fail("Seat was turned into a record, which generates equals and hashCode for you;"
                    + " keep Seat a class and write both methods yourself");
        }
        if (Seat.class.getSuperclass() != Object.class) {
            fail("Seat extends " + Seat.class.getSuperclass().getSimpleName()
                    + "; keep Seat a plain class and write both methods in Seat itself");
        }
        Method method = null;
        try {
            method = Seat.class.getDeclaredMethod(name, parameterTypes);
        } catch (NoSuchMethodException e) {
            fail("Seat does not declare " + name + "; it still uses the version inherited from Object");
        }
        if (method.isBridge() || method.isSynthetic()) {
            fail("Seat." + name + " was generated by the compiler, not written in Seat; write it yourself");
        }
    }

    @Test
    void equalsFollowsTheContract() {
        assertDeclares("equals", Object.class);
        Seat a = new Seat("A", 1);
        Seat b = new Seat("A", 1);
        Seat c = new Seat("A", 1);
        assertTrue(a.equals(a), "equals must be reflexive");
        assertTrue(a.equals(b) && b.equals(a), "equal seats must be equal both ways");
        assertTrue(b.equals(c) && a.equals(c), "equals must be transitive");
        assertFalse(a.equals(null), "equals must return false for null");
        assertFalse(a.equals("A1"), "a Seat is never equal to a String");
        assertNotEquals(a, new Seat("A", 2));
        assertNotEquals(a, new Seat("B", 1));
    }

    @Test
    void aSeatWithNoRowYetIsComparedSafely() {
        assertDeclares("equals", Object.class);
        Seat unassigned = new Seat(null, 3);
        assertTrue(unassigned.equals(new Seat(null, 3)), "use Objects.equals so a null row compares safely");
        assertFalse(unassigned.equals(new Seat("A", 3)), "a null row is not equal to a real row");
        assertFalse(new Seat("A", 3).equals(unassigned), "a real row is not equal to a null row");
    }

    @Test
    void equalSeatsHaveEqualHashCodes() {
        assertDeclares("hashCode");
        assertEquals(new Seat("A", 1).hashCode(), new Seat("A", 1).hashCode(),
                "equal objects must have equal hash codes");
        assertEquals(new Seat(null, 3).hashCode(), new Seat(null, 3).hashCode(),
                "use Objects.hash so a null row hashes safely");
        // Java allows unequal objects to share a hash code, so these are not contract rules. They
        // check this part's task: hashCode is built from both row and number with Objects.hash.
        // A constant, or a hash that ignores a field, puts many seats in one bucket.
        assertNotEquals(new Seat("A", 1).hashCode(), new Seat("A", 2).hashCode(),
                "hashCode ignores number; build it from both row and number with Objects.hash");
        assertNotEquals(new Seat(null, 1).hashCode(), new Seat(null, 2).hashCode(),
                "hashCode ignores number when row is null; build it from both fields with Objects.hash");
        assertNotEquals(new Seat("A", 1).hashCode(), new Seat("B", 1).hashCode(),
                "hashCode ignores row; build it from both row and number with Objects.hash");
        assertNotEquals(new Seat("A", 1).hashCode(), new Seat(null, 1).hashCode(),
                "hashCode ignores row; build it from both row and number with Objects.hash");
    }

    @Test
    void anEqualSeatIsFoundInAHashSetAndAsAHashMapKey() {
        assertDeclares("equals", Object.class);
        assertDeclares("hashCode");
        Set<Seat> booked = new HashSet<>();
        booked.add(new Seat("C", 4));
        assertTrue(booked.contains(new Seat("C", 4)), "an equal seat must be found in the set");

        Map<Seat, String> holders = new HashMap<>();
        holders.put(new Seat("C", 4), "ana");
        holders.put(new Seat("C", 4), "ben");
        assertEquals(1, holders.size(), "equal seats are one key");
        assertEquals("ben", holders.get(new Seat("C", 4)));
    }
}
